class EncoderBackbone:
    """Encoder weights (joints_embed / blocks / norm / pos & temp embed) and
    init logic shared by both pretraining and downstream transformers.

    Kept as a shared base class so the encoder submodule attribute names
    (`joints_embed`, `blocks`, `norm`, `pos_embed`, `temp_embed`) are identical
    across both classes — this is what lets a pretrained checkpoint transfer
    to the downstream model via `load_state_dict(strict=False)`.
    """

    def _build_encoder(self, dim_in, dim_feat, depth, num_heads, mlp_ratio,
                       num_frames, num_joints, patch_size, t_patch_size,
                       qkv_bias, qk_scale, drop_rate, attn_drop_rate,
                       drop_path_rate, norm_layer):
        # MAE encoder specifics
        self.joints_embed = SkeleEmbed(dim_in, dim_feat, num_frames, num_joints, patch_size, t_patch_size)
        self.pos_drop = nn.Dropout(p=drop_rate)
        dpr = [x.item() for x in torch.linspace(0, drop_path_rate, depth)]  # stochastic depth decay rule
        self.blocks = nn.ModuleList([
            Block(
                dim=dim_feat, num_heads=num_heads, mlp_ratio=mlp_ratio, qkv_bias=qkv_bias, qk_scale=qk_scale,
                drop=drop_rate, attn_drop=attn_drop_rate, drop_path=dpr[i], norm_layer=norm_layer)
            for i in range(depth)])
        self.norm = norm_layer(dim_feat)

        self.temp_embed = nn.Parameter(torch.zeros(1, num_frames // t_patch_size, 1, dim_feat))
        self.pos_embed = nn.Parameter(torch.zeros(1, 1, num_joints // patch_size, dim_feat))
        trunc_normal_(self.temp_embed, std=.02)
        trunc_normal_(self.pos_embed, std=.02)

    def _init_weights(self, m):
        if isinstance(m, nn.Linear):
            # we use xavier_uniform following official JAX ViT:
            torch.nn.init.xavier_uniform_(m.weight)
            if isinstance(m, nn.Linear) and m.bias is not None:
                nn.init.constant_(m.bias, 0)
        elif isinstance(m, nn.LayerNorm):
            nn.init.constant_(m.bias, 0)
            nn.init.constant_(m.weight, 1.0)


