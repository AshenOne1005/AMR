# Pretraining model: encoder + MAE-style decoder, motion-aware masking
# ---------------------------------------------------------------------------
class PretrainTransformer(EncoderBackbone, nn.Module):
    def __init__(self, dim_in=3, dim_feat=256, decoder_dim_feat=256,
                 depth=8, decoder_depth=5, num_heads=8, mlp_ratio=4,
                 num_frames=120, num_joints=25, patch_size=1, t_patch_size=4,
                 qkv_bias=True, qk_scale=None, drop_rate=0., attn_drop_rate=0.,
                 drop_path_rate=0., norm_layer=nn.LayerNorm, norm_skes_loss=False,
                 patch_ratio=6, decoder_attn_mode='sigmoid',
                 decoder_attn_alpha=1., decoder_attn_temperature=1.):
        super().__init__()
        self.dim_feat = dim_feat

        self.num_frames = num_frames
        self.num_joints = num_joints
        self.patch_size = patch_size
        self.t_patch_size = t_patch_size

        self.norm_skes_loss = norm_skes_loss

        self.patch_ratio = patch_ratio
        assert isinstance(self.patch_ratio, int) and self.patch_ratio >= 1, \
            f"patch_ratio must be a positive integer, got {self.patch_ratio}"
        assert num_frames % t_patch_size == 0, \
            f"num_frames ({num_frames}) must be divisible by t_patch_size ({t_patch_size})"
        assert (num_frames // t_patch_size) % self.patch_ratio == 0, \
            f"num_frames // t_patch_size ({num_frames // t_patch_size}) must be divisible by patch_ratio ({self.patch_ratio})"
        assert num_joints % patch_size == 0, \
            f"num_joints ({num_joints}) must be divisible by patch_size ({patch_size})"

        # ------------------------------------------------------------------
        # MAE encoder specifics
        self._build_encoder(dim_in, dim_feat, depth, num_heads, mlp_ratio,
                            num_frames, num_joints, patch_size, t_patch_size,
                            qkv_bias, qk_scale, drop_rate, attn_drop_rate,
                            drop_path_rate, norm_layer)

        # ------------------------------------------------------------------
        # MAE decoder specifics
        self.decoder_embed = nn.Linear(dim_feat, decoder_dim_feat, bias=True)

        self.mask_token = nn.Parameter(torch.zeros(1, 1, 1, decoder_dim_feat))
        trunc_normal_(self.mask_token, std=.02)

        self.decoder_temp_embed = nn.Parameter(torch.zeros(1, num_frames // (t_patch_size * self.patch_ratio), 1, decoder_dim_feat))
        self.decoder_pos_embed = nn.Parameter(torch.zeros(1, 1, num_joints // patch_size, decoder_dim_feat))
        trunc_normal_(self.decoder_temp_embed, std=.02)
        trunc_normal_(self.decoder_pos_embed, std=.02)

        self.decoder = nn.ModuleList([
            DecBlock(
                dim=dim_feat, num_heads=num_heads, mlp_ratio=mlp_ratio, qkv_bias=qkv_bias, qk_scale=qk_scale,
                drop=drop_rate, attn_drop=attn_drop_rate, drop_path=0., norm_layer=norm_layer,
                attn_mode=decoder_attn_mode, attn_alpha=decoder_attn_alpha,
                attn_temperature=decoder_attn_temperature)
            for i in range(decoder_depth)])

        self.decoder_norm = norm_layer(decoder_dim_feat)

        self.decoder_pred = nn.Sequential(
            nn.Linear(decoder_dim_feat, decoder_dim_feat),
            nn.LayerNorm(decoder_dim_feat),
            nn.GELU(),
            nn.Linear(decoder_dim_feat, decoder_dim_feat),
            nn.LayerNorm(decoder_dim_feat),
            nn.GELU(),
            nn.Linear(decoder_dim_feat, dim_in * patch_size * t_patch_size * self.patch_ratio)
        )

        # ------------------------------------------------------------------
        # Initialize weights
        self.apply(self._init_weights)

    def motion_aware_random_masking(self, x, x_orig, mask_ratio, tau):
        """
        Perform per-sample random masking by per-sample shuffling.
        Per-sample shuffling is done by argsort random noise.
        x: [NM, L, D], sequence
        x_orig: patchified original skeleton sequence
        """
        NM, L, D = x.shape  # batch, length, dim
        _, TP, VP, _ = x_orig.shape

        len_keep = int(L * (1 - mask_ratio))

        x_orig_motion = torch.zeros_like(x_orig)
        x_orig_motion[:, 1:, :, :] = torch.abs(x_orig[:, 1:, :, :] - x_orig[:, :-1, :, :])
        x_orig_motion[:, 0, :, :] = x_orig_motion[:, 1, :, :]
        x_orig_motion = x_orig_motion.mean(dim=[3])  # NM, TP, VP
        x_orig_motion = x_orig_motion.reshape(NM, L)

        x_orig_motion = x_orig_motion / (torch.max(x_orig_motion, dim=-1, keepdim=True).values * tau + 1e-8)

        x_orig_motion_prob = F.softmax(x_orig_motion, dim=-1)

        noise = torch.log(x_orig_motion_prob) - torch.log(-torch.log(torch.rand(NM, L, device=x.device) + 1e-8) + 1e-8)  # gumble

        # noise = torch.rand(N, L, device=x.device)  # noise in [0, 1]

        # sort noise for each sample
        ids_shuffle = torch.argsort(
            noise, dim=1
        )  # ascend: small is keep, large is remove
        ids_restore = torch.argsort(ids_shuffle, dim=1)

        # keep the first subset
        ids_keep = ids_shuffle[:, :len_keep]

        x_masked = torch.gather(x, dim=1, index=ids_keep.unsqueeze(-1).repeat(1, 1, D))

        # generate the binary mask: 0 is keep, 1 is remove
        mask = torch.ones([NM, L], device=x.device)
        mask[:, :len_keep] = 0
        # unshuffle to get the binary mask
        mask = torch.gather(mask, dim=1, index=ids_restore)

        return x_masked, mask, ids_restore, ids_keep

    def random_masking(self, x, mask_ratio):
        """
        Perform per-sample random masking by per-sample shuffling.
        Per-sample shuffling is done by argsort random noise.
        x: [N, L, D], sequence
        """
        N, L, D = x.shape  # batch, length, dim
        len_keep = int(L * (1 - mask_ratio))

        noise = torch.rand(N, L, device=x.device)  # noise in [0, 1]

        # sort noise for each sample
        ids_shuffle = torch.argsort(
            noise, dim=1
        )  # ascend: small is keep, large is remove
        ids_restore = torch.argsort(ids_shuffle, dim=1)

        # keep the first subset
        ids_keep = ids_shuffle[:, :len_keep]
        x_masked = torch.gather(x, dim=1, index=ids_keep.unsqueeze(-1).repeat(1, 1, D))

        # generate the binary mask: 0 is keep, 1 is remove
        mask = torch.ones([N, L], device=x.device)
        mask[:, :len_keep] = 0
        # unshuffle to get the binary mask
        mask = torch.gather(mask, dim=1, index=ids_restore)

        return x_masked, mask, ids_restore, ids_keep

    def forward_encoder(self, x, mask_ratio, motion_aware_tau):
        x_orig = self.patchify(x)

        # embed skeletons
        x = self.joints_embed(x)

        NM, TP, VP, _ = x.shape

        # add pos & temp embed
        x = x + self.pos_embed[:, :, :VP, :] + self.temp_embed[:, :TP, :, :]

        # masking: length -> length * mask_ratio
        x = x.reshape(NM, TP * VP, -1)

        if motion_aware_tau > 0:
            x_orig = x_orig.reshape(shape=(NM, TP, VP, -1))
            x, mask, ids_restore, ids_keep = self.motion_aware_random_masking(x, x_orig, mask_ratio, motion_aware_tau)
        else:
            x, mask, ids_restore, ids_keep = self.random_masking(x, mask_ratio)

        # apply Transformer blocks
        for idx, blk in enumerate(self.blocks):
            x = blk(x)

        x = self.norm(x)

        return x, mask, ids_restore, ids_keep

    def forward_decoder(self, mem, coef):
        NM = mem.shape[0]
        TP = self.joints_embed.t_grid_size
        VP = self.joints_embed.grid_size

        # embed tokens
        mem = self.decoder_embed(mem)
        C = mem.shape[-1]

        x = self.mask_token.repeat(NM, TP // self.patch_ratio, VP, 1)
        x = x + self.decoder_pos_embed + self.decoder_temp_embed

        x = x.reshape(NM, (TP * VP) // self.patch_ratio, -1)

        for idx, blk in enumerate(self.decoder):
            x = blk(x, mem)

        y = self.decoder_norm(x)
        y = self.decoder_pred(y)

        return y

    def patchify(self, imgs, patch_size=None, t_patch_size=None):
        """
        imgs: (N, T, V, 3)
        x: (N, L, t_patch_size * patch_size * 3)
        """
        p = patch_size if patch_size is not None else self.patch_size
        u = t_patch_size if t_patch_size is not None else self.t_patch_size
        NM, T, V, C = imgs.shape
        assert V % p == 0 and T % u == 0
        VP = V // p
        TP = T // u

        x = imgs.reshape(shape=(NM, TP, u, VP, p, C))
        x = torch.einsum("ntuvpc->ntvupc", x)
        x = x.reshape(shape=(NM, TP * VP, u * p * C))
        return x

    # ---------------------------------------------------------------------------
    # Eq.(3) Motion energy of joints over a temporal window of length n:
    # e = 1/(n-1) * ||s_t - mu||^2  (x: NM,T,V,C)
    # ---------------------------------------------------------------------------
    def motion_energy(self, x: torch.Tensor, n: int) -> torch.Tensor:
        NM, T, V, C = x.shape
        pad = (-T) % n
        xt = F.pad(x, (0, 0, 0, 0, 0, pad))                            # (NM,T',V,C)
        Tw = xt.shape[1] // n
        xw = xt.reshape(NM, Tw, n, V, C)
        e = (xw - xw.mean(2, keepdim=True)).pow(2).sum(2) / (n - 1)    # (NM,Tw,V,C)
        # e = e.mean(dim=-1)  # (NM,Tw,V)
        # e = e.sum(dim=-1)
        return e


    # ---------------------------------------------------------------------------
    # Eq.(4) w = 1 / (1 + k*e_t/e), where e_t is the mean energy over all
    # windows (adaptive threshold)
    # ---------------------------------------------------------------------------
    def weight_fn(self, e: torch.Tensor, k: float = 0.01, eps: float = 1e-8) -> torch.Tensor:
        e_t = e.mean(dim=(1, 2), keepdim=True)                         # (NM,1,1)
        w = torch.sqrt(e / (e + k * e_t + eps)) # equivalent to w = sqrt(1 / (1 + k*e_t/e)), more stable
        return w


    # ---------------------------------------------------------------------------
    # Multi-scale windows (4, 8, 12): upsample weights to frame level and fuse.
    # Default fusion is mean; pass `fusion_weights` (same length as
    # `window_scales`, summing to 1) for weighted fusion.
    # ---------------------------------------------------------------------------
    @torch.no_grad()
    def adaptive_weights(self,x: torch.Tensor,
                         window_scales: Sequence[int] = (4, 8, 12),
                         k: float = 0.01,
                         fusion_weights: Optional[Sequence[float]] = None) -> torch.Tensor:
        """x: (NM,T,V,C) -> W: (NM,T,V,C) frame-level joint importance, broadcast on C, values in (0,1]"""
        NM, T, V, C = x.shape
        if fusion_weights is None:
            fusion_weights = [1.0 / len(window_scales)] * len(window_scales)
        assert len(fusion_weights) == len(window_scales)
        scale_ws = []
        for n, fw in zip(window_scales, fusion_weights):
            w = self.weight_fn(self.motion_energy(x, n), k)            # (NM,Tw,V,C)
            w[:, T // n:] = 1.0                                        # set weights of padded windows to 1 (empty slice when pad=0)
            scale_ws.append(w.repeat_interleave(n, dim=1)[:, :T] * fw) # (NM,T,V,C)
        w = torch.stack(scale_ws).sum(0)         
        return w                      # (NM,T,V,C)
        # return w.unsqueeze(-1).expand(NM, T, V, C)



    def extract_motion(self, x, motion_stride=1):
        """
        imgs: [NM, T, V, 3]
        """
        # generate motion
        x_motion = torch.zeros_like(x)
        x_motion[:, :-motion_stride, :, :] = x[:, motion_stride:, :, :] - x[:, :-motion_stride, :, :]
        x_motion[:, -motion_stride:, :, :] = 0
        return x_motion

    def cal_loss(self, pred, target, coef):
        NM = target.shape[0]
        TP = self.joints_embed.t_grid_size
        VP = self.joints_embed.grid_size

        target = self.patchify(target, patch_size=self.patch_size, t_patch_size=self.t_patch_size * self.patch_ratio)
        coef = self.patchify(coef, patch_size=self.patch_size, t_patch_size=self.t_patch_size * self.patch_ratio)

        pred = pred.reshape(NM, -1)
        target = target.reshape(NM, -1)
        coef = coef.reshape(NM, -1)
        

        loss = (pred - target) ** 2
        loss = coef * loss
        loss = loss.mean()

        return loss

    def norm_skeleton(self, imgs, eps=1e-8):
        """
        imgs: (N, T, V, 3)
        x: (N, L, t_patch_size * patch_size * 3)
        """
        NM, T, V, C = imgs.shape
        p = self.patch_size
        u = self.t_patch_size
        assert V % p == 0 and T % u == 0
        VP = V // p
        TP = T // u

        x = imgs.reshape(shape=(NM, TP, u, VP, p, C))

        mean = x.mean(dim=2, keepdim=True)
        var = x.var(dim=2, keepdim=True) 


        x = (x - mean) / torch.sqrt(var + eps)
        x = x.reshape(shape=(NM, T, V, C))

        return x

    def forward(self, x, mask_ratio=0.80, motion_stride=1, motion_aware_tau=0.75,
                fusion_weights=(0.34, 0.33, 0.33), **kwargs):
        N, C, T, V, M = x.shape

        x = x.permute(0, 4, 2, 3, 1).contiguous().view(N * M, T, V, C)

        with torch.autocast(device_type=x.device.type, enabled=False):
            target = self.norm_skeleton(x.float())
            coef = self.adaptive_weights(
                x.float(), window_scales=[4, 8, 12],
                k=0.01, fusion_weights=fusion_weights,
            )
        # target = self.norm_skeleton(x)
        # coef = self.adaptive_weights(x, window_scales=[4,8,12], k=0.01, fusion_weights=fusion_weights)

        latent, mask, ids_restore, ids_keep = self.forward_encoder(x, mask_ratio, motion_aware_tau)
        preds = self.forward_decoder(latent, coef)  # [NM, TP * VP, C]

        # loss = self.cal_loss(preds, target, coef)

        with torch.autocast(device_type=preds.device.type, enabled=False):
            loss = self.cal_loss(preds.float(), target, coef)

        return loss, preds, mask


