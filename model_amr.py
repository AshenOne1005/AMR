"""AMR model.

Layout:
  * Shared building blocks: `MLP`, `Attention`, `Block`,
    `CrossAttention`, `DecBlock`, `SkeleEmbed`, and the two action heads
    (`LinearProbeHead`, `FinetuneHead`).
  * `PretrainTransformer`: encoder + MAE-style decoder, motion-aware masking
    and reconstruction loss. `forward` returns `(loss, preds, mask)`.
  * `DownstreamTransformer`: encoder + action head. `forward` returns logits.

The encoder (`joints_embed`, `blocks`, `norm`, `pos_embed`, `temp_embed`) is
identical between the two classes — same module names, same shapes — so a
pretrained `PretrainTransformer` checkpoint loads into a `DownstreamTransformer`
via `load_state_dict(..., strict=False)` with no remapping required.
"""

