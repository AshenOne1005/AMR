# Action heads (downstream only)
class LinearProbeHead(nn.Module):
    def __init__(self, dim_feat=256, num_classes=60):
        super(LinearProbeHead, self).__init__()
        self.net = nn.Sequential(
            nn.BatchNorm1d(dim_feat, affine=False, eps=1e-6),
            nn.Linear(dim_feat, num_classes),
        )

    def forward(self, feat):
        '''
            Input: (N, J*C) pooled features
        '''
        return self.net(feat)


class FinetuneHead(nn.Module):
    def __init__(self, dropout_ratio=0., dim_feat=512, num_classes=60, hidden_dim=2048):
        super(FinetuneHead, self).__init__()
        self.net = nn.Sequential(
            nn.Dropout(p=dropout_ratio),
            nn.Linear(dim_feat, hidden_dim),
            nn.BatchNorm1d(hidden_dim, momentum=0.1),
            nn.ReLU(inplace=True),
            nn.Linear(hidden_dim, num_classes),
        )

    def forward(self, feat):
        '''
            Input: (N, J*C) pooled features
        '''
        return self.net(feat)

class DownstreamTransformer(EncoderBackbone, nn.Module):
    def __init__(self, dim_in=3, num_classes=120, dim_feat=256,
                 depth=8, num_heads=8, mlp_ratio=4,
                 num_frames=120, num_joints=25, patch_size=1, t_patch_size=4,
                 qkv_bias=True, qk_scale=None, drop_rate=0., attn_drop_rate=0.,
                 drop_path_rate=0., norm_layer=nn.LayerNorm, protocol='linprobe',
                 return_features=False):
        super().__init__()
        self.num_classes = num_classes
        self.dim_feat = dim_feat

        self.num_frames = num_frames
        self.num_joints = num_joints
        self.patch_size = patch_size
        self.t_patch_size = t_patch_size

        self.protocol = protocol
        self.return_features = return_features

        # ------------------------------------------------------------------
        # MAE encoder specifics
        self._build_encoder(dim_in, dim_feat, depth, num_heads, mlp_ratio,
                            num_frames, num_joints, patch_size, t_patch_size,
                            qkv_bias, qk_scale, drop_rate, attn_drop_rate,
                            drop_path_rate, norm_layer)

        # ------------------------------------------------------------------
        # Downstream head
        if protocol == 'linprobe':
            self.head = LinearProbeHead(dim_feat=dim_feat * (num_joints // patch_size),
                                        num_classes=num_classes)
        elif protocol == 'finetune':
            self.head = FinetuneHead(dropout_ratio=0.3, dim_feat=dim_feat*num_joints, num_classes=num_classes)
        else:
            raise TypeError('Unrecognized evaluation protocol: {!r}'.format(protocol))

        # ------------------------------------------------------------------
        # Initialize weights
        self.apply(self._init_weights)

    def _run_encoder(self, x):
        """Run the full encoder backbone (all tokens, no masking).

        Input:  x of shape (N, C, T, V, M).
        Output: per-token features of shape (N, M, TP, VP, C) — the patch
        token sequence right after the final norm, before any pooling.
        Downstream heads expect this 5-D layout (they do their own pooling).
        """
        N, C, T, V, M = x.shape
        x = x.permute(0, 4, 2, 3, 1).contiguous().view(N * M, T, V, C)

        # embed skeletons
        x = self.joints_embed(x)

        NM, TP, VP, _ = x.shape

        # add pos & temp embed
        x = x + self.pos_embed[:, :, :VP, :] + self.temp_embed[:, :TP, :, :]

        x = x.reshape(NM, TP * VP, -1)

        # apply Transformer blocks
        for idx, blk in enumerate(self.blocks):
            x = blk(x)

        x = self.norm(x)

        x = x.reshape(N, M, TP, VP, -1)
        return x

    @staticmethod
    def _pool_features(feat):
        """Pool 5-D patch tokens (N, M, T, V, C) -> (N, V*C).

        Mean over time (T) and persons (M). Matches the pooling the original
        downstream model applied before its head.
        """
        N, M, T, V, C = feat.shape
        feat = feat.mean(dim=[1, 2])
        feat = feat.reshape(N, -1)           
        
        return feat

    def forward(self, x):
        feat = self._run_encoder(x)
        feat = self._pool_features(feat)
        if self.return_features:
            return feat
        return self.head(feat)
